// Package genmodelsdev generates the hosted part of the curated catalog
// from the models.dev data.
//
// The models.dev data is a JSON object keyed by the provider's id, and
// every provider holds the models it serves. The generator reads that
// file and writes the Go file the catalog holds. It never reaches the
// network: fetching the data is a separate, deliberate step.
package genmodelsdev

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// provider is one provider of the models.dev data.
type provider struct {
	// ID is the provider's id.
	ID string `json:"id"`
	// Name is the provider's display name.
	Name string `json:"name"`
	// API is the provider's API base URL.
	API string `json:"api"`
	// Env names the environment variables that hold the provider's key.
	Env []string `json:"env"`
	// Models are the models the provider serves, by id.
	Models map[string]model `json:"models"`
}

// model is one model of the models.dev data.
type model struct {
	// ID is the model's id.
	ID string `json:"id"`
	// Name is the model's display name.
	Name string `json:"name"`
	// Reasoning reports whether the model reasons.
	Reasoning bool `json:"reasoning"`
	// ToolCall reports whether the model makes tool calls.
	ToolCall bool `json:"tool_call"`
	// Temperature reports whether the model takes a temperature.
	Temperature bool `json:"temperature"`
	// Modalities are the modalities the model reads and writes.
	Modalities struct {
		Input []string `json:"input"`
	} `json:"modalities"`
	// Limit is the model's context window and output limit.
	Limit struct {
		Context int `json:"context"`
		Output  int `json:"output"`
	} `json:"limit"`
}

// entry is one generated hosted model.
type entry struct {
	Provider     string
	ModelID      string
	Name         string
	BaseURL      string
	Env          []string
	ContextLimit int
	MaxOutput    int
	Reasoning    bool
	ToolCall     bool
	Temperature  bool
	Inputs       []string
}

// Generate reads the models.dev file and writes the Go file.
func Generate(input, output string) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("reading %s: %w", input, err)
	}
	var providers map[string]provider
	if err := json.Unmarshal(data, &providers); err != nil {
		return fmt.Errorf("parsing %s: %w", input, err)
	}
	entries := collect(providers)
	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	b.WriteString("package catalog\n\n")
	b.WriteString("// hostedModels is the hosted part of the curated catalog.\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// The entries come from the models.dev data in %s.\n", filepath.Base(filepath.Dir(input))+"/"+filepath.Base(input))
	b.WriteString("var hostedModels = []hostedEntry{\n")
	for _, e := range entries {
		writeEntry(&b, e)
	}
	b.WriteString("}\n")
	if err := os.WriteFile(output, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", output, err)
	}
	return nil
}

// collect turns the providers into the entries of the catalog.
//
// The entries are sorted by the provider and then by the model, so the
// generated file does not change when the data does not.
func collect(providers map[string]provider) []entry {
	var out []entry
	ids := make([]string, 0, len(providers))
	for id := range providers {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		p := providers[id]
		providerID := p.ID
		if providerID == "" {
			providerID = id
		}
		modelIDs := make([]string, 0, len(p.Models))
		for modelID := range p.Models {
			modelIDs = append(modelIDs, modelID)
		}
		sort.Strings(modelIDs)
		for _, modelID := range modelIDs {
			m := p.Models[modelID]
			id := m.ID
			if id == "" {
				id = modelID
			}
			out = append(out, entry{
				Provider:     providerID,
				ModelID:      id,
				Name:         m.Name,
				BaseURL:      p.API,
				Env:          p.Env,
				ContextLimit: m.Limit.Context,
				MaxOutput:    m.Limit.Output,
				Reasoning:    m.Reasoning,
				ToolCall:     m.ToolCall,
				Temperature:  m.Temperature,
				Inputs:       m.Modalities.Input,
			})
		}
	}
	return out
}

// writeEntry writes one entry of the generated file.
func writeEntry(b *strings.Builder, e entry) {
	fmt.Fprintf(b, "\t{\n")
	fmt.Fprintf(b, "\t\tProvider:     %q,\n", e.Provider)
	fmt.Fprintf(b, "\t\tModelID:      %q,\n", e.ModelID)
	if e.Name != "" {
		fmt.Fprintf(b, "\t\tName:         %q,\n", e.Name)
	}
	if e.BaseURL != "" {
		fmt.Fprintf(b, "\t\tBaseURL:      %q,\n", e.BaseURL)
	}
	if len(e.Env) > 0 {
		fmt.Fprintf(b, "\t\tEnv:          []string{%s},\n", quoteList(e.Env))
	}
	if e.ContextLimit > 0 {
		fmt.Fprintf(b, "\t\tContextLimit: %d,\n", e.ContextLimit)
	}
	if e.MaxOutput > 0 {
		fmt.Fprintf(b, "\t\tMaxOutput:    %d,\n", e.MaxOutput)
	}
	fmt.Fprintf(b, "\t\tReasoning:    %t,\n", e.Reasoning)
	fmt.Fprintf(b, "\t\tToolCall:     %t,\n", e.ToolCall)
	fmt.Fprintf(b, "\t\tTemperature:  %t,\n", e.Temperature)
	if len(e.Inputs) > 0 {
		fmt.Fprintf(b, "\t\tInputs:       []string{%s},\n", quoteList(e.Inputs))
	}
	fmt.Fprintf(b, "\t},\n")
}

// quoteList renders a list of names for the generated file.
func quoteList(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return strings.Join(quoted, ", ")
}
